const { chromium } = require("playwright");
const path = require("path");
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 900 } });
  const errors = [];
  p.on("pageerror", (e) => errors.push(e.message));
  p.on("dialog", (d) => d.accept());
  await p.goto("file://" + path.resolve(__dirname, "../index.html"));
  await p.click('nav button[data-tab="importar"]');
  await p.setInputFiles("#csvFile", path.resolve(__dirname, "../ejemplos/banco-ejemplo.csv"));
  await p.click("#confirmImport");
  await p.setInputFiles("#csvFile", path.resolve(__dirname, "../ejemplos/banco-ejemplo.csv"));
  await p.click("#confirmImport");
  const msg = await p.textContent("#preview");
  await p.click('nav button[data-tab="metas"]');
  await p.fill('[data-amt="1"]', "1200");
  await p.click('[data-contrib="1"]');
  await p.click('nav button[data-tab="resumen"]');
  await p.selectOption("#rMonth", "2026-10");
  const kin = await p.textContent("#kIn");
  await p.screenshot({ path: path.resolve(__dirname, "../captura-resumen.png"), fullPage: true });
  const n = await p.evaluate(() => JSON.parse(localStorage.getItem("finanzas.v1")).txs.length);
  await b.close();
  if (errors.length) throw new Error(errors.join("\n"));
  if (n !== 13) throw new Error("expected 13 txs (dedupe), got " + n);
  if (!msg.includes("13 duplicados")) throw new Error("dedupe message: " + msg);
  if (!kin.includes("650")) throw new Error("income " + kin);
  console.log("smoke OK", n, kin);
})().catch((e) => { console.error(e); process.exit(1); });
