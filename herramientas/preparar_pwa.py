"""Prepare the repo's web apps to be installable and work offline (PWA) on GitHub Pages.

Generates, from the repo root:
  - icons/          app icons (180 for iOS, 192 and 512 for Android)
  - sw.js           service worker: network first (always fresh when online), cache when offline
  - manifest.webmanifest   installable "Panel de vida" (start = 28-panel-vida/)
and adds to each app's index.html (only once) the iOS home-screen tags + ../pwa.js.

Re-run after adding a new app or a new runtime file:   python herramientas/preparar_pwa.py
On file:// (double click) nothing changes: service workers only run over http(s).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APPS = [
    "28-panel-vida", "26-ritmo", "27-paso", "15-habitos/app", "10-gym-tracker",
    "21-idiomas-plan", "11-finanzas", "12-mapa-viajes", "25-habilidades/mecanografia",
]
MARK = "<!-- pwa -->"


def icons() -> list[str]:
    from PIL import Image, ImageDraw, ImageFont

    out = ROOT / "icons"
    out.mkdir(exist_ok=True)
    font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    names = []
    for size, name, radius in [(180, "apple-touch-icon.png", 0), (192, "icon-192.png", 0.22), (512, "icon-512.png", 0.22)]:
        img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(img)
        bg = (30, 35, 32, 255)
        if radius:
            d.rounded_rectangle([0, 0, size - 1, size - 1], radius=int(size * radius), fill=bg)
        else:  # iOS rounds the corners itself
            d.rectangle([0, 0, size, size], fill=bg)
        font = ImageFont.truetype(font_path, int(size * 0.56))
        d.text((size / 2, size / 2 + size * 0.02), "V", font=font, fill=(243, 244, 241, 255), anchor="mm")
        # small accent dot = "a day well lived"
        r = size * 0.07
        d.ellipse([size * 0.70 - r, size * 0.26 - r, size * 0.70 + r, size * 0.26 + r], fill=(180, 155, 224, 255))
        img.save(out / name)
        names.append(f"icons/{name}")
    return names


def runtime_files() -> list[str]:
    files = ["./", "index.html", "pwa.js", "manifest.webmanifest"]
    for app in APPS:
        base = ROOT / app
        files.append(f"{app}/")
        for p in sorted(base.iterdir()):
            if p.is_file() and p.suffix in {".html", ".css", ".js"}:
                files.append(f"{app}/{p.name}")
        vendor = base / "vendor"
        if vendor.is_dir():
            files += [str(p.relative_to(ROOT)) for p in sorted(vendor.rglob("*")) if p.is_file() and p.suffix in {".js", ".css", ".png"}]
    return files


SW = """/* Service worker of Mix_ideas (generated by herramientas/preparar_pwa.py — do not edit by hand).
   Network first with a 4 s timeout: online you always get the latest version; offline, the cached copy. */
const CACHE = "mix-ideas-v1";
const FILES = %s;

self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => Promise.all(FILES.map((f) => c.add(f).catch(() => null)))).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("mix-ideas") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try {
      const res = await Promise.race([fetch(req), new Promise((_, rej) => setTimeout(() => rej(new Error("timeout")), 4000))]);
      if (res && res.ok) cache.put(req, res.clone());
      return res;
    } catch (err) {
      const hit = (await cache.match(req, { ignoreSearch: true })) ||
        (req.mode === "navigate" ? (await cache.match(new URL("index.html", req.url).href)) : null);
      if (hit) return hit;
      throw err;
    }
  })());
});
"""

PWA_JS = """/* Registers the shared service worker (only over http/https, e.g. GitHub Pages) and asks the browser
   to keep this site's data (localStorage) even when space is low. Does nothing when opened with a double click. */
(function () {
  var me = document.currentScript && document.currentScript.src;
  if (!me || !/^https?:/.test(location.protocol)) return;
  if ("serviceWorker" in navigator) {
    window.addEventListener("load", function () {
      navigator.serviceWorker.register(new URL("sw.js", me).href, { scope: new URL("./", me).href }).catch(function () {});
    });
  }
  if (navigator.storage && navigator.storage.persist) navigator.storage.persist().catch(function () {});
})();
"""


def patch_html(app: str) -> bool:
    page = ROOT / app / "index.html"
    html = page.read_text(encoding="utf-8")
    if MARK in html:
        return False
    rel = "../" * (app.count("/") + 1)
    tags = [MARK, f'<link rel="apple-touch-icon" href="{rel}icons/apple-touch-icon.png">']
    if "apple-mobile-web-app-capable" not in html:
        tags.append('<meta name="apple-mobile-web-app-capable" content="yes">')
    if app == "28-panel-vida":
        tags.append(f'<link rel="manifest" href="{rel}manifest.webmanifest">')
    tags.append(f'<script src="{rel}pwa.js" defer></script>')
    html = html.replace("</head>", "\n".join(tags) + "\n</head>", 1)
    page.write_text(html, encoding="utf-8")
    return True


def main() -> None:
    icon_files = icons()
    manifest = {
        "name": "Panel de vida", "short_name": "Vida", "lang": "es",
        "start_url": "./28-panel-vida/", "scope": "./", "display": "standalone",
        "background_color": "#EEEEEB", "theme_color": "#1E2320",
        "icons": [{"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png"},
                  {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any maskable"}],
    }
    (ROOT / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "pwa.js").write_text(PWA_JS, encoding="utf-8")
    files = runtime_files() + icon_files
    (ROOT / "sw.js").write_text(SW % json.dumps(files, ensure_ascii=False, indent=1), encoding="utf-8")
    patched = [a for a in APPS if patch_html(a)]
    root_idx = ROOT / "index.html"
    if MARK not in root_idx.read_text(encoding="utf-8"):
        root_idx.write_text(root_idx.read_text(encoding="utf-8").replace(
            "</head>", f'{MARK}\n<link rel="manifest" href="manifest.webmanifest">\n<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">\n<script src="pwa.js" defer></script>\n</head>', 1), encoding="utf-8")
    print(f"{len(files)} ficheros en caché · apps parcheadas ahora: {patched or 'ninguna (ya estaban)'}")


if __name__ == "__main__":
    main()
