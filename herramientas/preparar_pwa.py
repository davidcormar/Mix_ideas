"""Prepare the repo's web apps to be installable and work offline (PWA) on GitHub Pages.

Generates, from the repo root:
  - icons/          app icons (180 for iOS, 192 and 512 for Android)
  - sw.js           service worker: network first (always fresh when online), cache when offline or after 4 s;
                    its cache name is a hash of the files, so re-run this after every change you deploy
  - manifest.webmanifest   installable "Panel de vida" (start = 28-panel-vida/)
and adds to each app's index.html (only once) the iOS home-screen tags + ../pwa.js.

Re-run after adding a new app or a new runtime file:   python herramientas/preparar_pwa.py
On file:// (double click) nothing changes: service workers only run over http(s).
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APPS = [
    "28-panel-vida", "26-ritmo", "27-paso", "15-habitos/app", "10-gym-tracker",
    "21-idiomas-plan", "11-finanzas", "12-mapa-viajes", "25-habilidades/mecanografia", "29-importar-salud",
]
MARK = "<!-- pwa -->"


def icons() -> list[str]:
    from PIL import Image, ImageDraw, ImageFont

    out = ROOT / "icons"
    out.mkdir(exist_ok=True)
    font_path = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
    names = []
    # radius 0 = full-bleed square: iOS rounds the corners itself, and Android crops maskable icons to its own shape
    for size, name, radius in [(180, "apple-touch-icon.png", 0), (192, "icon-192.png", 0.22), (512, "icon-512.png", 0.22), (512, "icon-maskable-512.png", 0)]:
        img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(img)
        bg = (30, 35, 32, 255)
        if radius:
            d.rounded_rectangle([0, 0, size - 1, size - 1], radius=int(size * radius), fill=bg)
        else:
            d.rectangle([0, 0, size, size], fill=bg)
        scale = 0.8 if name.startswith("icon-maskable") else 1  # keep the V and the dot inside the 80 % safe zone
        font = ImageFont.truetype(font_path, int(size * 0.56 * scale))
        d.text((size / 2, size / 2 + size * 0.02), "V", font=font, fill=(243, 244, 241, 255), anchor="mm")
        # small accent dot = "a day well lived"
        r, cx, cy = size * 0.07 * scale, size * (0.5 + 0.20 * scale), size * (0.5 - 0.24 * scale)
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=(180, 155, 224, 255))
        img.save(out / name)
        names.append(f"icons/{name}")
    return names


def runtime_files() -> list[str]:
    files = ["./", "index.html", "pwa.js", "manifest.webmanifest"]
    for app in APPS:
        base = ROOT / app
        files.append(f"{app}/")
        for p in sorted(base.iterdir()):
            if p.is_file() and p.suffix in {".html", ".css", ".js"}:
                files.append(f"{app}/{p.name}")
        vendor = base / "vendor"
        if vendor.is_dir():
            files += [str(p.relative_to(ROOT)) for p in sorted(vendor.rglob("*")) if p.is_file() and p.suffix in {".js", ".css", ".png"}]
    return files


SW = """/* Service worker of Mix_ideas (generated by herramientas/preparar_pwa.py — do not edit by hand).
   Network first: online you get the latest deploy (revalidated, not from the HTTP cache); offline, or with no answer
   after 4 s, the cached copy.
   - VERSION is a hash of every cached file: each deploy that re-runs the generator installs a fresh, complete copy
     (fetched with cache: "reload", so never from the browser's HTTP cache) and the old copy is deleted.
   - A file that cannot be downloaded during the install keeps its copy from the previous version.
   - Slow network and nothing cached: it keeps waiting for the network instead of failing at 4 s.
   - Folders: "app/" and "app/index.html" are the same page offline; "app" (no final slash) is sent to "app/". */
const VERSION = "%s";
const CACHE = "mix-ideas-" + VERSION;
const TIMEOUT_MS = 4000;
const FILES = %s;

self.addEventListener("install", (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await Promise.all(FILES.map(async (f) => {
      try {
        const res = await fetch(new Request(f, { cache: "reload" }));
        if (res.ok) return cache.put(f, res);
      } catch (err) { /* offline or flaky during the install */ }
      const old = await caches.match(f, { ignoreSearch: true });
      if (old) return cache.put(f, old);
    }));
    await self.skipWaiting();
  })());
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("mix-ideas") && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

async function fromCache(req) {
  const cache = await caches.open(CACHE);
  const hit = await cache.match(req, { ignoreSearch: true });
  if (hit || req.mode !== "navigate") return hit;
  const u = new URL(req.url);
  u.search = ""; u.hash = "";
  if (u.pathname.endsWith("/")) return cache.match(u.href + "index.html");
  if (u.pathname.endsWith("/index.html")) return cache.match(u.href.slice(0, -"index.html".length));
  if (await cache.match(u.href + "/")) return Response.redirect(u.href + "/", 302); // relative links need the slash
  return undefined;
}

self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || !req.url.startsWith(self.registration.scope)) return; // other sites and other repos: untouched
  let saved = Promise.resolve();
  // "no-cache" revalidates with the server (a cheap 304 when nothing changed): GitHub Pages sends max-age=600,
  // so without it a deploy could stay invisible for 10 minutes and pages could mix old and new files
  const net = fetch(req, { cache: "no-cache" }).then((res) => {
    // only whole, same-origin, non-redirected answers (a 206 or an opaque redirect cannot be replayed)
    if (res.status === 200 && res.type === "basic" && !res.redirected) {
      const copy = res.clone();
      saved = caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => null);
    }
    return res;
  });
  e.waitUntil(net.then(() => saved, () => null));
  e.respondWith((async () => {
    let timer;
    const late = new Promise((r) => { timer = setTimeout(r, TIMEOUT_MS, "late"); });
    try {
      const first = await Promise.race([net, late]);
      if (first !== "late") return first;
      return (await fromCache(req)) || net; // slow network: cached copy if there is one, otherwise keep waiting
    } catch (err) {
      const hit = await fromCache(req); // offline
      if (hit) return hit;
      throw err;
    } finally {
      clearTimeout(timer);
    }
  })());
});
"""

PWA_JS = """/* Registers the shared service worker (only over http/https, e.g. GitHub Pages) and asks the browser
   to keep this site's data (localStorage) even when space is low. Does nothing when opened with a double click.
   The scope is the repo root, so one worker serves every app, nested ones (15-habitos/app, 25-habilidades/mecanografia) too. */
(function () {
  var me = document.currentScript && document.currentScript.src;
  if (!me || !/^https?:/.test(location.protocol)) return;
  if ("serviceWorker" in navigator) {
    window.addEventListener("load", function () {
      navigator.serviceWorker.register(new URL("sw.js", me).href, { scope: new URL("./", me).href }).catch(function () {});
    });
  }
  var st = navigator.storage;
  if (st && st.persist && st.persisted) st.persisted().then(function (yes) { return yes || st.persist(); }).catch(function () {});
})();
"""


def version(files: list[str]) -> str:
    """Hash of the names and bytes of every cached file: changes on every deploy that changes something."""
    h = hashlib.sha256()
    for f in files:
        h.update(f.encode())
        p = ROOT / f
        if p.is_file():
            h.update(p.read_bytes())
    return h.hexdigest()[:12]


def patch_html(app: str) -> bool:
    page = ROOT / app / "index.html"
    html = page.read_text(encoding="utf-8")
    if MARK in html:
        return False
    rel = "../" * (app.count("/") + 1)
    tags = [MARK, f'<link rel="apple-touch-icon" href="{rel}icons/apple-touch-icon.png">']
    if "apple-mobile-web-app-capable" not in html:
        tags.append('<meta name="apple-mobile-web-app-capable" content="yes">')
    if app == "28-panel-vida":
        tags.append(f'<link rel="manifest" href="{rel}manifest.webmanifest">')
    tags.append(f'<script src="{rel}pwa.js" defer></script>')
    html = html.replace("</head>", "\n".join(tags) + "\n</head>", 1)
    page.write_text(html, encoding="utf-8")
    return True


def main() -> None:
    icon_files = icons()
    manifest = {
        "id": "./28-panel-vida/", "name": "Panel de vida", "short_name": "Vida", "lang": "es", "dir": "ltr",
        "description": "Tu vida en una pantalla: sueño, móvil, lectura, metas y revisión semanal, con tus apps del repo.",
        "start_url": "./28-panel-vida/", "scope": "./", "display": "standalone",
        "background_color": "#EEEEEB", "theme_color": "#1E2320",
        "icons": [{"src": "icons/icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
                  {"src": "icons/icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
                  {"src": "icons/icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"}],
    }
    (ROOT / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (ROOT / "pwa.js").write_text(PWA_JS, encoding="utf-8")
    files = runtime_files() + icon_files
    (ROOT / "sw.js").write_text(SW % (version(files), json.dumps(files, ensure_ascii=False, indent=1)), encoding="utf-8")
    patched = [a for a in APPS if patch_html(a)]
    root_idx = ROOT / "index.html"
    if MARK not in root_idx.read_text(encoding="utf-8"):
        root_idx.write_text(root_idx.read_text(encoding="utf-8").replace(
            "</head>", f'{MARK}\n<link rel="manifest" href="manifest.webmanifest">\n<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">\n<script src="pwa.js" defer></script>\n</head>', 1), encoding="utf-8")
    print(f"{len(files)} ficheros en caché · versión {version(files)} · apps parcheadas ahora: {patched or 'ninguna (ya estaban)'}")


if __name__ == "__main__":
    main()
